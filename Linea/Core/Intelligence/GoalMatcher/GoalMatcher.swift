//
//  GoalMatcher.swift
//  Linea
//
//  «Насколько задача мэтчится с целью» из брифа. Явная связь (`goalID`)
//  всегда сильнее: матчер только ПРЕДЛАГАЕТ связь — «Похоже, относится к: …
//  [Связать]» — и никогда не проставляет её сам, иначе приоритизация
//  перестанет быть объяснимой.
//
//  Сейчас это `ConceptGoalMatcher`: понятия вместо слов и цель целиком —
//  детерминированно, офлайн, проверяется тестами. Модель на телефоне, если
//  появится, станет ещё одной реализацией этого протокола, без правок экранов
//  и движков.
//

import Foundation

nonisolated struct GoalMatch: Hashable, Sendable {
    let goalID: UUID
    /// Чем выше, тем увереннее совпадение; подсказывать есть смысл от 0,5.
    let score: Double
}

nonisolated protocol GoalMatcher: Sendable {
    /// Лучшее совпадение среди целей или nil, если ничего похожего нет.
    func bestMatch(for taskTitle: String, in goals: [LineaGoal]) -> GoalMatch?
}
